//go:build ignore

// gentokens 从 docs/design/tokens/tokens.json 生成 tokens_gen.go。tokens.json 是唯一来源。
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func goName(k string) string {
	parts := strings.Split(k, "-")
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

var rgbaRe = regexp.MustCompile(`^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$`)

func color(v string) (string, bool) {
	if strings.HasPrefix(v, "#") && len(v) == 7 {
		return fmt.Sprintf("ui.Hex(%q)", v), true
	}
	if m := rgbaRe.FindStringSubmatch(v); m != nil {
		a, _ := strconv.ParseFloat(m[4], 32)
		return fmt.Sprintf("ui.RGBA(%s, %s, %s, %s)", m[1], m[2], m[3], strconv.FormatFloat(a, 'g', -1, 32)), true
	}
	return "", false // 阴影等复合值不进调色板
}

func px(v string) string { return strings.TrimSuffix(v, "px") }

func main() {
	raw, err := os.ReadFile("../../docs/design/tokens/tokens.json")
	if err != nil {
		panic(err)
	}
	var t struct {
		Color  map[string]map[string]string
		Font   map[string]string
		Space  map[string]string
		Radius map[string]string
		Size   map[string]string
	}
	if err := json.Unmarshal(raw, &t); err != nil {
		panic(err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by gentokens.go from docs/design/tokens/tokens.json. DO NOT EDIT.\n\npackage main\n\nimport \"github.com/egoist/mygo/ui\"\n\n")
	keys := []string{}
	for k := range t.Color["light"] {
		if _, ok := color(t.Color["light"][k]); ok {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	b.WriteString("// Palette 是一套主题的颜色令牌。\ntype Palette struct {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s ui.Color\n", goName(k))
	}
	b.WriteString("}\n\n")
	for _, theme := range []string{"light", "dark"} {
		fmt.Fprintf(&b, "var %s = Palette{\n", goName(theme))
		for _, k := range keys {
			c, _ := color(t.Color[theme][k])
			fmt.Fprintf(&b, "\t%s: %s,\n", goName(k), c)
		}
		b.WriteString("}\n\n")
	}
	group := func(prefix string, m map[string]string, skip func(string) bool) {
		ks := make([]string, 0, len(m))
		for k := range m {
			ks = append(ks, k)
		}
		sort.Strings(ks)
		b.WriteString("const (\n")
		for _, k := range ks {
			if skip != nil && skip(k) {
				continue
			}
			fmt.Fprintf(&b, "\t%s%s = %s\n", prefix, goName(k), px(m[k]))
		}
		b.WriteString(")\n\n")
	}
	group("Font", t.Font, func(k string) bool { return k == "ui" || k == "mono" })
	group("Space", t.Space, nil)
	group("Radius", t.Radius, nil)
	group("Size", t.Size, nil)
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(fmt.Errorf("%v\n%s", err, b.String()))
	}
	if err := os.WriteFile("tokens_gen.go", out, 0o644); err != nil {
		panic(err)
	}
}
